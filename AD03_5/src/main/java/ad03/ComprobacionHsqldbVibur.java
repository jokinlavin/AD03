package ad03;

import org.vibur.dbcp.ViburDBCPDataSource;
import java.sql.*;

public class ComprobacionHsqldbVibur {
    public static void main(String[] args) {
        
        // Creamos un pool de conexiones Vibur 
        ViburDBCPDataSource pool = new ViburDBCPDataSource();
        pool.setJdbcUrl("jdbc:hsqldb:file:./data/dbformacion_check;shutdown=true");
        pool.setUsername("SA");
        pool.setPassword("");
        pool.setPoolInitialSize(1);
        pool.setPoolMaxSize(5);
        pool.setConnectionTimeoutInMs(5000);
        pool.start();

        try {
            try (Connection con = pool.getConnection()) {
                // Comprobamos que la conexión es correcta
                boolean valida = con.isValid(2);
                System.out.println("Connection.isValid(2): " + valida);
                if (!valida) throw new SQLException("La conexión no es válida.");

                try (Statement st = con.createStatement()) {
                    st.executeUpdate("CREATE TABLE IF NOT EXISTS comprobacion (" +
                            " id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY," +
                            " mensaje VARCHAR(200) NOT NULL)");
                }
                try (PreparedStatement ps = con.prepareStatement(
                        "INSERT INTO comprobacion(mensaje) VALUES (?)")) {
                    ps.setString(1, "JDBC con HSQLDB y Vibur");
                    ps.executeUpdate();
                }
                try (PreparedStatement ps = con.prepareStatement(
                        "SELECT id,mensaje FROM comprobacion ORDER BY id");
                    // Listamos los registros
                    ResultSet rs = ps.executeQuery()) {
                    System.out.println("Filas recuperadas:");
                    while (rs.next()) System.out.printf("id=%d | mensaje=%s%n",
                        rs.getInt("id"), rs.getString("mensaje"));
                }
            }
        } catch (SQLException e) {
            System.err.println("Error en HSQLDB/Vibur DBCP: " + e.getMessage());
        } finally {
            // Para asegurarnos que se cierra siempre
            pool.terminate();
            System.out.println("Pool Vibur DBCP finalizado.");
        }
    }
}
